/**
 * Per-page onboarding tours for the lecturer area.
 *
 * Same conventions as the staff tours (app/staff/tours/definitions.ts):
 * steps target `[data-tour="…"]` anchors or stable selectors; a step without
 * `element` renders as a centered card for UI that only appears
 * conditionally (modals, alerts, expanded rows).
 */

const step = (
  element: string | undefined,
  title: string,
  description: string,
): TourStep =>
  element
    ? { element, popover: { title, description } }
    : { popover: { title, description } };

// Same, but when the element is not on screen yet (e.g. the TA card that
// appears only after pressing "เพิ่ม TA") the step shows as a centered card
// instead of being skipped, so first-time visitors still get the lesson.
const softStep = (
  element: string,
  title: string,
  description: string,
): TourStep => ({ element, fallbackCenter: true, popover: { title, description } });

