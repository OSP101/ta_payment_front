import type { DriveStep } from "driver.js";

/**
 * Per-page onboarding tours for the staff area.
 *
 * Steps target `[data-tour="…"]` anchors placed in each page (plus a few
 * stable selectors like sidebar hrefs). A step without `element` renders as
 * a centered card — used for page intros and for explaining UI that only
 * appears conditionally (modals, expanded rows).
 */
export type StaffTourDef = {
  /** Unique key — also used for the "seen" flag in localStorage. */
  key: string;
  match: (path: string) => boolean;
  steps: DriveStep[];
};

const step = (
  element: string | undefined,
  title: string,
  description: string,
): DriveStep =>
  element
    ? { element, popover: { title, description } }
    : { popover: { title, description } };

