/**
 * Per-page onboarding tours for the TA area.
 * Same conventions as app/staff/tours/ and app/lecturer/tours/.
 * Step texts are msg() keys; the tour engine translates them at render.
 */

const step = (
  element: string | undefined,
  title: string,
  description: string,
): TourStep =>
  element
    ? { element, popover: { title, description } }
    : { popover: { title, description } };

// Shows as a centered card when the element is not on screen right now
// (checklist gone after approval, banners, collapsed sections).
const softStep = (
  element: string,
  title: string,
  description: string,
): TourStep => ({ element, fallbackCenter: true, popover: { title, description } });

